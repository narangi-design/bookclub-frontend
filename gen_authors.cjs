// ── Read mockBooks.ts ─────────────────────────────────────────────────────────
const raw = fs.readFileSync('d:/Study/Frontend/book-worm/src/mocks/mockBooks.ts', 'utf8')
const books = JSON.parse(
  raw
    .replace(/^\/\/[^\n]*\n/gm, '')
    .replace(/export const mockBooks = /, '')
    .replace(/;\s*$/, '')
)

// Verify all authors are covered
const missing = []
for (const b of books) {
  if (b.author && !CANONICAL[b.author]) missing.push(`[${b.id}] "${b.author}"`)
}
if (missing.length) { console.error('MISSING AUTHORS:\n' + missing.join('\n')); process.exit(1) }

// ── Build sorted authors list ─────────────────────────────────────────────────
const canonicalSet = new Set(Object.values(CANONICAL))
const sorted = [...canonicalSet].sort((a, b) => a.localeCompare(b, 'ru'))
const authorToId = {}
sorted.forEach((name, i) => { authorToId[name] = i + 1 })

// ── Generate mockAuthors.ts ───────────────────────────────────────────────────
const authorsLines = sorted.map((name, i) =>
  `  { id: ${i + 1}, value: ${JSON.stringify(name)} },`
)
const authorsTs = `export const mockAuthors = [\n${authorsLines.join('\n')}\n]\n`
fs.writeFileSync('d:/Study/Frontend/book-worm/src/mocks/mockAuthors.ts', authorsTs)
console.log(`\u2713 mockAuthors.ts \u2014 ${sorted.length} \u0430\u0432\u0442\u043e\u0440\u043e\u0432`)

// ── Generate updated mockBooks.ts ─────────────────────────────────────────────
const updatedBooks = books.map(b => {
  let author_id = null
  if (b.author) {
    const canonical = CANONICAL[b.author]
    author_id = authorToId[canonical]
  }
  const title = b.id === 57 ? '\u0418\u0441\u043f\u043e\u0432\u0435\u0434\u044c \xab\u043d\u0435\u043f\u043e\u043b\u043d\u043e\u0446\u0435\u043d\u043d\u043e\u0433\u043e \u0447\u0435\u043b\u043e\u0432\u0435\u043a\u0430\xbb' : b.title
  return {
    id: b.id, title, author_id,
    country: b.country, added_by_user_id: b.added_by_user_id,
    added_at: b.added_at, status: b.status,
    elected_poll_id: b.elected_poll_id, elected_at: b.elected_at
  }
})

const booksLines = updatedBooks.map(b => '  ' + JSON.stringify(b) + ',')
const booksTs = `export const mockBooks = [\n${booksLines.join('\n')}\n]\n`
fs.writeFileSync('d:/Study/Frontend/book-worm/src/mocks/mockBooks.ts', booksTs)
console.log(`\u2713 mockBooks.ts \u2014 ${updatedBooks.length} \u043a\u043d\u0438\u0433, author \u2192 author_id`)
